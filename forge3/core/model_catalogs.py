# Image-generation and voice/audio models cannot answer in a text room — they
# return no chat content at all, which the UI can only render as a blank bubble.
# The snapshot above no longer lists any, but a live /models refresh or a pasted
# JSON overlay can still offer them, so the picker filters on these tokens too.
# Matching is per token, not substring: 'inkling' must not read as 'kling', and
# vision-*input* models (deepseek-v4-flash-vision-exp) still reply in text and stay.
MEDIA_ONLY_TOKENS: frozenset[str] = frozenset({
    # image generation
    "image", "images", "imagen", "dalle", "diffusion", "sdxl", "sd35",
    "flux", "sora", "veo", "midjourney", "seedream", "seedance",
    "recraft", "ideogram", "pixart", "kandinsky",
    # voice / audio
    "audio", "voice", "tts", "stt", "speech", "whisper", "transcribe",
    "realtime", "orpheus", "kokoro", "elevenlabs", "playai", "cartesia",
    "chatterbox", "bark", "vall",
})

_MEDIA_SPLIT = re.compile(r"[^a-z0-9]+")


def is_media_only_model(model: str) -> bool:
    """True when a model id names an image or voice model rather than a chat model."""
    tail = str(model or "").casefold().rsplit("/", 1)[-1]
    return any(token in MEDIA_ONLY_TOKENS for token in _MEDIA_SPLIT.split(tail) if token)
